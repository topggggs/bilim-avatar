import 'dotenv/config';
import seed from '../config/test.ru.json';
import { configSchema } from '../packages/core/src/index.js';
import { writtenProfile } from '../packages/core/src/written.js';
import {
  createAnalyzer,
  configuredAnalysisProvider,
  analysisProviderLabel,
} from '../apps/api/src/analysis.js';
const provider = configuredAnalysisProvider();
const analyze = createAnalyzer();
if (!analyze) {
  console.error(
    `Не задан ${provider === 'gemini' ? 'GEMINI_API_KEY' : 'OPENAI_API_KEY'} в серверном .env`,
  );
  process.exitCode = 2;
} else {
  const config = configSchema.parse(seed);
  // Synthetic work examples only. Never use employee answers for a connection check.
  const examples = [
    'До смены сверю план и допуски, осмотрю СИЗ. Если допуска нет, опасную работу не начну: сообщу руководителю и согласую безопасную задачу.',
    'Сверю размеры и отметки с актуальной версией чертежа, зафиксирую расхождения. До согласования с инженером спорный участок выполнять не буду.',
    'Спокойно назову факт нарушения, возможный риск и предложу остановить операцию. При несогласии зафиксирую проблему и обращусь к ответственному инженеру.',
    'Уточню причину задержки и срочность, проверю загрузку своей бригады. С руководителями согласую помощь, не оставляя свои работы без ответственного.',
    'Не буду пропускать обязательную проверку. Объясню, какой риск она контролирует, и предложу сэкономить время на организации следующей операции.',
    'Уточню назначение указания, проверю проект и технологическую карту. Если сомнение осталось, покажу конкретное расхождение инженеру и согласую решение.',
    'От точности моих отметок зависит монтаж следующего этажа. До передачи участка проверяю размеры и сообщаю принимающей бригаде все отклонения.',
    'Оценю риск и свои полномочия. Безопасное обратимое решение приму в их пределах, а опасную операцию остановлю и свяжусь с дежурным ответственным.',
    'Запишу фактические объёмы и замечания до ухода, сверю записи с исполнителями. Дальше выделю последние десять минут смены для журнала.',
    'Передам факт и риск владельцу участка, при срочной опасности остановлю опасное действие. Уточню, кто отвечает за исправление, и проверю обратную связь.',
    'Соберу факты о повторяющемся браке, сравню смены и условия, проверю причины с бригадой. После исправления измерю повторяемость дефекта на следующих работах.',
    'Проверю вывод по измерениям и критериям приёмки. Если данных недостаточно, запрошу проверку инженера и поясню, что именно вызывает сомнение.',
    'Сверю предложенную перестановку с технологической картой и рисками. Без согласованного решения порядок не изменю, предложу безопасный вариант ускорения.',
    'Покажу новичку приём по шагам, объясню риски и ограничения. Попрошу повторить под наблюдением, проверю результат и дам обратную связь.',
    'Остановлю работы на спорном участке, сверю армирование с актуальным проектом, зафиксирую отклонение. Объясню бригаде риск и получу согласование инженера до продолжения.',
  ];
  try {
    const report = await analyze(
      Object.fromEntries(config.questions.map((q, i) => [q.id, examples[i]])),
      config,
    );
    const result = writtenProfile(report, config);
    console.log(
      JSON.stringify(
        {
          status: 'ok',
          provider: analysisProviderLabel(provider),
          model: report.model,
          percentages: result.percentages,
        },
        null,
        2,
      ),
    );
  } catch {
    console.error('Проверка ИИ не прошла. Проверьте ключ, доступ к модели, сеть и квоту сервиса.');
    process.exitCode = 1;
  }
}
